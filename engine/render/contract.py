def plane_material(plane):
    bpy = _bpy_module()
    if bpy is None or plane is None:
        return None
    try:
        bo = getattr(plane, "blenderObject", None)
        slots = getattr(bo, "material_slots", None)
        if not slots:
            return None
        return slots[0].material
    except Exception:
        return None


def apply_material_image(mat, image_path) -> bool:
    import os
    bpy = _bpy_module()
    if bpy is None or mat is None or not image_path:
        return False
    try:
        if not os.path.isfile(image_path):
            return False
        nt = getattr(mat, "node_tree", None)
        if nt is None:
            return False
        tex = None
        for n in nt.nodes:
            if n.type == "TEX_IMAGE":
                tex = n
                break
        if tex is None:
            return False
        img = bpy.data.images.load(image_path, check_existing=True)
        tex.image = img
        for n in nt.nodes:
            if n.type == "MIX":
                try:
                    for inp in n.inputs:
                        if inp.name == "Factor":
                            inp.default_value = 1.0
                except Exception:
                    pass
        return True
    except Exception:
        return False


