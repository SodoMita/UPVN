def find_ui_font(filename: str = None):
    """Locate a UI typeface for BAKING (bpy-capable contexts only)."""
    if filename is None:
        filename = UI_FONT_REGULAR
    try:
        from pathlib import Path
        here = Path(__file__).resolve()
        # Search in blend/fonts/ relative to project root
        cands = [
            here.parents[2] / "blend" / "fonts" / filename,
            here.parents[2] / "game" / "fonts" / filename,
            here.parents[2] / "assets" / "fonts" / filename,
        ]
        # Also try basename only (for fonts/lato/Lato-Regular.ttf -> Lato-Regular.ttf)
        import os
        base = os.path.basename(filename)
        cands.append(here.parents[2] / "blend" / "fonts" / base)
        cands.append(here.parents[2] / "game" / "fonts" / base)
        
        try:
            import bpy
            bbase = Path(bpy.app.binary_path).resolve().parent
            cands += [
                bbase / "5.0" / "datafiles" / "fonts" / filename,
                bbase / "5.0" / "datafiles" / "fonts" / base,
                bbase / "datafiles" / "fonts" / filename,
                bbase / "datafiles" / "fonts" / base,
            ]
        except Exception:
            pass
        cands.append(Path("/usr/share/fonts/truetype/dejavu") / filename)
        cands.append(Path("/usr/share/fonts/truetype/dejavu") / base)
        cands.append(Path(f"/usr/share/fonts/truetype/lato/{base}"))
        
        for c in cands:
            if c.exists():
                return str(c)
    except Exception:
        pass
    return None


def style_font_curve(data, bold: bool = False, shear: float | None = None, font_name: str | None = None) -> str:
    """Apply text style to a bpy FONT curve."""
    if data is None:
        return "skipped"
    status = "font-not-found"
    try:
        target = font_name or (UI_FONT_BOLD if bold else UI_FONT_REGULAR)
        fn = find_ui_font(target)
        if fn:
            import bpy
            font = bpy.data.fonts.load(fn, check_existing=True)
            if font is not None:
                data.font = font
                status = "dejavu"
    except Exception:
        pass
    try:
        data.extrude = TEXT_EXTRUDE
        data.bevel_depth = TEXT_BEVEL
        data.bevel_resolution = TEXT_BEVEL_RESOLUTION
    except Exception:
        pass
    if shear is not None:
        try:
            data.shear = shear
        except Exception:
            pass
    return status


